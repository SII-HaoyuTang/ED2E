#!/usr/bin/env python3
"""
ED2E training script — DDP + bf16 AMP + gradient accumulation.

Data layout expected:
    <data-dir>/
        packed_stage3/          ← Stage3PackedDataset (sharded)
        split.json              ← {"train": [...], "val": [...], "test": [...]}
        energy_stats.json       ← {"mean": (6,), "std": (6,), "target_names": [...]}

Generated by scripts/preprocess_edbench.py.

Single-GPU usage
----------------
::

    python scripts/train.py \
        --data-dir  data/ed_energy_5w \
        --csv-path  data/ed_energy_5w/raw/ed_energy_5w.csv \
        --out-dir   runs/stage6_k3 \
        --num-bblocks 3 --batch-size 8 --epochs 100 --device cuda

Multi-GPU (DDP via torchrun)
-----------------------------
::

    torchrun --nproc_per_node=8 scripts/train.py \
        --data-dir  data/ed_energy_5w \
        --csv-path  data/ed_energy_5w/raw/ed_energy_5w.csv \
        --out-dir   runs/stage6_ddp \
        --num-bblocks 3 --batch-size 8 --grad-accum 2 \
        --epochs 100 --num-workers 4

Effective batch size = batch_size × num_gpus × grad_accum.

Resume from checkpoint:
    torchrun ... --resume runs/stage6_ddp/best.pt
"""
