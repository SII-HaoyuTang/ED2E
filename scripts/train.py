# Dataset wrapper
# ══════════════════════════════════════════════════════════════════════════════

class LabeledPackedDataset(Dataset):
    """
    Wraps Stage3PackedDataset, attaching energy labels from CSV.
    Returns (Stage3Sample, label_normalised) pairs.
    """

    def __init__(
        self,
        packed_dir: str,
        csv_path: str,
        mol_ids: List[str],
        norm_stats: Dict[str, np.ndarray],
    ) -> None:
        self.label_map = load_energy_labels(csv_path)
        mean = norm_stats["mean"]   # (6,)
        std  = norm_stats["std"]    # (6,)

        # Intersect mol_ids with both packed dataset content and CSV labels
        packed_mol_set = set(Stage3PackedDataset(packed_dir).mol_ids)
        self.mol_ids = [m for m in mol_ids if m in self.label_map and m in packed_mol_set]
        if not self.mol_ids:
            raise ValueError(
                f"No labelled molecules found in packed dataset. "
                f"Packed dataset has {len(packed_mol_set)} molecules; "
                f"check csv_path and that preprocessing is complete."
            )

        self.base    = Stage3PackedDataset(packed_dir, mol_ids=self.mol_ids)
        self._mean   = mean
        self._std    = std

    def __len__(self) -> int:
        return len(self.mol_ids)

    def __getitem__(self, idx: int) -> Tuple[Stage3Sample, np.ndarray]:
        sample = self.base[idx]
        mol_id = self.mol_ids[idx]
        raw    = self.label_map[mol_id]           # (6,) float32
        normed = (raw - self._mean) / self._std   # (6,) float32
        return sample, normed


def labeled_collate(batch):
    """
    Returns CPU tensors only.  The training loop moves them to the target
    device with non_blocking=True after the DataLoader yields them, which
    lets DMA transfers overlap with the preceding GPU work.
    """
    samples, labels = zip(*batch)
    tb      = collate_stage3_samples(list(samples))   # CPU Stage3TensorBatch
    targets = torch.tensor(np.stack(labels), dtype=torch.float32)
    return tb, targets


# ══════════════════════════════════════════════════════════════════════════════
# Training helpers
# ══════════════════════════════════════════════════════════════════════════════

@torch.no_grad()
def _evaluate(
    model: nn.Module,
    loader: DataLoader,
    device: torch.device,
    norm_stats: Dict[str, np.ndarray],
    num_targets: int,
    target_names: Tuple[str, ...],
    amp_ctx,
) -> Dict[str, float]:
    """Compute per-target MAE in Hartree (denormalised)."""
    model.eval()
    mean_t = torch.tensor(norm_stats["mean"], dtype=torch.float32, device=device)
    std_t  = torch.tensor(norm_stats["std"],  dtype=torch.float32, device=device)

    abs_errors: List[torch.Tensor] = []
    total_loss = 0.0
    n_batches  = 0

    for batch, targets in loader:
        batch   = batch.to(device, non_blocking=True)
        targets = targets.to(device, non_blocking=True)

        with amp_ctx:
            out  = model(batch)
            pred = out["energy_pred"].float()   # cast back to fp32 for metrics

        loss = sum(
            F.huber_loss(pred[:, t], targets[:, t], delta=1.0)
            for t in range(num_targets)
        ) / num_targets
        total_loss += float(loss)
        n_batches  += 1

        pred_raw    = pred * std_t + mean_t
        targets_raw = targets * std_t + mean_t
        abs_errors.append((pred_raw - targets_raw).abs().cpu())

    mae_per_target = torch.cat(abs_errors, dim=0).mean(dim=0)   # (T,)
    result = {"loss": total_loss / max(n_batches, 1)}
    for i, name in enumerate(target_names):
        result[f"mae_{name}"] = float(mae_per_target[i])
    result["mae_mean"] = float(mae_per_target.mean())
    return result


def _save_checkpoint(
    path: str,
    model: ED2EModel,
    norm_stats: Dict[str, np.ndarray],
    epoch: int,
    val_mae: np.ndarray,
) -> None:
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    torch.save(
        {
            "config":     model.cfg,
            "state_dict": model.state_dict(),
            "norm_mean":  norm_stats["mean"],
            "norm_std":   norm_stats["std"],
            "epoch":      epoch,
            "val_mae":    val_mae,
        },
        path,
    )


